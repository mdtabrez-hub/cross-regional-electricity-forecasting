"""Data inspection: inventory, quality report and machine-readable metadata.

Outputs (data/metadata/): data_inventory.csv, dataset_metadata.json,
data_quality_report.md, quality_by_region_year.csv, imputation_codes_by_region.csv
"""
from __future__ import annotations

import json

import numpy as np
import pandas as pd

from .common import DATA_META, DATA_PROCESSED, DATA_RAW, load_config, save_json


def main() -> None:
    cfg = load_config()
    raw = pd.read_parquet(DATA_RAW / "out_eia930__hourly_operations.parquet")
    dp = json.load(open(DATA_RAW / "pudl_parquet_datapackage.json"))
    res = next(r for r in dp["resources"] if r["name"] == "out_eia930__hourly_operations")
    src = next(s for s in res.get("sources", dp["sources"]) if s["name"] == "eia930") if res.get("sources") else None
    allreg = pd.read_csv(DATA_PROCESSED / "regions_all.csv", index_col=0)
    panel = pd.read_parquet(DATA_PROCESSED / "panel.parquet")

    # Inventory of all BAs in the raw table (full period) + study-window statistics.
    full = raw.groupby("balancing_authority_code_eia", observed=True).agg(
        first_utc=("datetime_utc", "min"), last_utc=("datetime_utc", "max"), rows_full=("datetime_utc", "size"))
    full.index = full.index.astype(str)
    inv = allreg.join(full, how="outer", rsuffix="_full")
    inv.index.name = "region"
    inv.to_csv(DATA_META / "data_inventory.csv")

    panel["year"] = (panel.time_utc - pd.Timedelta("1h")).dt.year  # hour-ending -> interval start
    q = panel.groupby(["region", "year"], observed=True).agg(
        hours=("time_utc", "size"),
        reported_missing=("reported", lambda s: s.isna().mean()),
        flagged=("eval_ok", lambda s: 1 - s.mean()),
        input_missing_after_causal_screen=("x_input", lambda s: s.isna().mean()),
        mean_mw=("target", "mean"),
        ba_forecast_missing=("ba_forecast", lambda s: s.isna().mean()),
    ).reset_index()
    q.to_csv(DATA_META / "quality_by_region_year.csv", index=False)

    codes = panel.assign(code=panel.imputation_code.fillna("none")).pivot_table(
        index="region", columns="code", values="time_utc", aggfunc="size", fill_value=0, observed=True)
    codes.to_csv(DATA_META / "imputation_codes_by_region.csv")

    sel = allreg[allreg.selected]
    n_hours = panel.groupby("region", observed=True).size().iloc[0]
    meta = {
        "dataset": "EIA Form 930 hourly balancing authority operations (PUDL out_eia930__hourly_operations)",
        "pudl_version": dp.get("version"),
        "pudl_created": dp.get("created"),
        "pudl_git_sha": dp.get("git_sha"),
        "retrieval_date": "2026-10-16",
        "download_base_url": cfg["data"]["pudl_base_url"],
        "licence_pudl": dp.get("licenses"),
        "licence_source": src.get("license_raw") if src else None,
        "source_doi": src.get("doi") if src else None,
        "source_concept_doi": src.get("concept_doi") if src else None,
        "documentation": src.get("documentation") if src else None,
        "raw_table_rows": int(len(raw)),
        "raw_table_bas": int(raw.balancing_authority_code_eia.nunique()),
        "raw_time_coverage_utc": [str(raw.datetime_utc.min()), str(raw.datetime_utc.max())],
        "timestamp_convention": "UTC, hour-ending (PUDL: 'Timestamp at the end of the hour')",
        "units": "MWh per hour (equivalent to average MW)",
        "sampling_frequency": "1 hour",
        "study_window_utc": [cfg["data"]["start_utc"], cfg["data"]["end_utc"]],
        "study_hours_per_region": int(n_hours),
        "selected_regions": sorted(sel.index.tolist()),
        "n_selected_regions": int(len(sel)),
        "panel_rows": int(len(panel)),
        "panel_eval_ok_share": float(panel.eval_ok.mean()),
        "panel_input_missing_share": float(panel.x_input.isna().mean()),
        "duplicate_timestamps_in_selected": int(sel.duplicate_timestamps.sum()),
        "variables": {f["name"]: f.get("description", "") for f in res["schema"]["fields"]},
    }
    save_json(meta, DATA_META / "dataset_metadata.json")

    lines = ["# Data Quality Report", "",
             f"Generated by `src/inspect_data.py` from PUDL {dp.get('version')} (retrieved 2026-10-16).", "",
             "## Raw table", "",
             f"* Rows: {len(raw):,}; balancing authorities: {raw.balancing_authority_code_eia.nunique()}; "
             f"UTC coverage {raw.datetime_utc.min()} – {raw.datetime_utc.max()}.",
             "* Timestamps are UTC and hour-ending, so daylight-saving transitions do not create duplicate or "
             "missing timestamps in the panel; local-time calendar features are derived per BA from its reporting "
             "time zone (some BAs report in a zone different from their geographic location, e.g. MISO uses "
             "America/New_York; this only affects calendar features).",
             f"* Duplicate (region, timestamp) pairs among selected BAs: {int(sel.duplicate_timestamps.sum())}.",
             "* Units: MWh in each hour (= average MW). Demand is BA-calculated as net generation minus net "
             "interchange and excludes behind-the-meter generation, so rooftop PV growth appears as demand reduction.",
             "", "## Region selection", "",
             f"{len(sel)} of {len(allreg)} BAs present in 2019–2025 met all pre-specified criteria "
             "(configs/experiment.yaml).", "",
             "| Region | Exclusion reasons | Mean MW |", "|---|---|---|"]
    for r, row in allreg[~allreg.selected].iterrows():
        mw = "" if pd.isna(row.mean_demand_mw) else f"{row.mean_demand_mw:,.0f}"
        lines.append(f"| {r} | {row.exclusion_reasons.rstrip(';')} | {mw} |")
    lines += ["", "## Selected regions (study window)", "",
              "| Region | Interconnect | Mean MW | Reported coverage | PUDL-flagged share | BA forecast coverage |",
              "|---|---|---|---|---|---|"]
    for r, row in sel.sort_values("mean_demand_mw", ascending=False).iterrows():
        lines.append(f"| {r} | {row.interconnect_code_eia} | {row.mean_demand_mw:,.0f} | {row.reported_coverage:.4f} | "
                     f"{row.flagged_share:.4f} | {row.ba_forecast_coverage:.4f} |")
    tot = codes.sum()
    lines += ["", "## PUDL imputation codes in the selected panel (hours)", ""]
    lines += [f"* {c}: {int(v):,}" for c, v in tot.sort_values(ascending=False).items()]
    lines += ["", "## Known limitations", "",
              "* No weather covariates are included in EIA-930.",
              "* BA boundaries and membership change over time (e.g. utilities joining SWPP/MISO, Western Energy "
              "Imbalance Market participation does not change BA demand but BA consolidations do). Level shifts "
              "are part of the temporal distribution shift studied.",
              "* EIA-930 values are operational data subject to revision; PUDL screening (Ruggles et al., 2020 "
              "method) flags anomalies but cannot guarantee correctness.",
              "* BA day-ahead forecasts have unknown issuance times and use weather forecasts; they are a reference, "
              "not a like-for-like benchmark.",
              "* BAs are spatially correlated; observations across regions are not independent."]
    (DATA_META / "data_quality_report.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
