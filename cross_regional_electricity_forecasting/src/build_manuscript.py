"""Build the Word manuscript (and PDF) from manuscript/sections/*.md.

Pipeline
  1. ``{{key}}`` placeholders are filled from results/manuscript_numbers.json, generated by
     src/manuscript_numbers.py from saved metric files, so every number in the text is
     traceable to an experiment output. Unknown keys abort the build.
  2. ``[[TABLE:name]]`` inserts results/tables/name.md; ``[[FIGURE:name]]`` inserts
     figures/name.png with its manifest caption. Figures and tables are numbered in order.
  3. pandoc converts Markdown (LaTeX math -> native Word equations; citations via
     citeproc + literature/verified_references.bib).
  4. python-docx enforces formatting: Times New Roman, 12 pt justified body with 1.5 line
     spacing, heading hierarchy, 2.54 cm margins, page numbers, readable tables/captions.
  5. LibreOffice renders a PDF for visual inspection (font substitution: Liberation Serif is
     metric-compatible with Times New Roman when the latter is not installed).

Usage: python -m src.build_manuscript [--source manuscript/manuscript_source.md] [--out manuscript/manuscript_final.docx]
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path

import pandas as pd
from docx import Document
from docx.enum.section import WD_ORIENT  # noqa: F401
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_LINE_SPACING
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

from .common import FIG_DIR, RESULTS, ROOT, TABLE_DIR

MS = ROOT / "manuscript"
FONT = "Times New Roman"


def fill_numbers(text: str) -> str:
    nums = json.load(open(RESULTS / "manuscript_numbers.json"))
    missing = sorted(set(k for k in re.findall(r"\{\{([^}]+)\}\}", text) if k not in nums))
    if missing:
        raise KeyError(f"unknown number keys: {missing}")
    return re.sub(r"\{\{([^}]+)\}\}", lambda m: str(nums[m.group(1)]), text)


def insert_objects(text: str) -> str:
    figman = pd.read_csv(FIG_DIR / "figure_manifest.csv").set_index("figure")
    tabman = pd.read_csv(TABLE_DIR / "table_manifest.csv").set_index("table")
    counters = {"fig": 0, "tab": 0}
    fig_ids, tab_ids = {}, {}

    # assign numbers in order of first appearance of the directive
    for kind, name in re.findall(r"\[\[(FIGURE|TABLE|TABLECAP):([\w\-]+)", text):
        if kind == "TABLECAP":
            kind = "TABLE"
        if kind == "FIGURE" and name not in fig_ids:
            counters["fig"] += 1
            fig_ids[name] = counters["fig"]
        if kind == "TABLE" and name not in tab_ids:
            if re.match(r"table_[A-Z]\d", name):
                tab_ids[name] = name.split("_")[1]  # appendix tables keep their own label (A1, A2, ...)
                continue
            counters["tab"] += 1
            tab_ids[name] = counters["tab"]

    def fig(m):
        name = m.group(1)
        cap = figman.loc[name, "caption"]
        return (f"\n\n![]({(FIG_DIR / (name + '.png')).as_posix()}){{width=16cm}}\n\n"
                f"::: {{custom-style=\"Figure Caption\"}}\n**Fig. {fig_ids[name]}.** {cap}\n:::\n\n")

    def tab(m):
        name = m.group(1)
        md = (TABLE_DIR / f"{name}.md").read_text().split("\n", 2)[2]  # drop bold caption line
        cap = re.sub(r"^Table [A-Z]?\d+[a-z]?\.\s*", "", tabman.loc[name, "caption"])
        return (f"\n\n::: {{custom-style=\"Table Caption\"}}\n**Table {tab_ids[name]}.** {cap}\n:::\n\n{md}\n\n")

    text = re.sub(r"\[\[TABLECAP:([\w\-]+)\|([^\]]+)\]\]",
                  lambda m: f"\n\n::: {{custom-style=\"Table Caption\"}}\n**Table {tab_ids[m.group(1)]}.** {m.group(2)}\n:::\n\n", text)
    text = re.sub(r"\[\[FIGURE:([\w\-]+)\]\]", fig, text)
    text = re.sub(r"\[\[TABLE:([\w\-]+)\]\]", tab, text)
    # cross references: @fig:name / @tab:name -> numbers
    text = re.sub(r"\{fig:([\w\-]+)\}", lambda m: str(fig_ids[m.group(1)]), text)
    text = re.sub(r"\{tab:([\w\-]+)\}", lambda m: str(tab_ids[m.group(1)]), text)
    return text


def reference_doc(path: Path):
    """Start from pandoc's default reference.docx (keeps its table/list styles) and set fonts."""
    with open(path, "wb") as fh:
        subprocess.run(["pandoc", "--print-default-data-file", "reference.docx"], stdout=fh, check=True)
    d = Document(path)
    for name in ("Normal", "Body Text", "First Paragraph", "Compact", "Bibliography", "Title", "Abstract",
                 "Heading 1", "Heading 2", "Heading 3", "Table Caption", "Image Caption"):
        try:
            s = d.styles[name]
        except KeyError:
            continue
        s.font.name = FONT
        s.font.color.rgb = RGBColor(0, 0, 0)
        rpr = s.element.get_or_add_rPr()
        rf = rpr.find(qn("w:rFonts"))
        if rf is None:
            rf = OxmlElement("w:rFonts")
            rpr.insert(0, rf)
        for a in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
            rf.set(qn(a), FONT)
        for a in ("w:asciiTheme", "w:hAnsiTheme", "w:cstheme", "w:eastAsiaTheme"):
            if rf.get(qn(a)) is not None:
                del rf.attrib[qn(a)]
        if name in ("Normal", "Body Text", "First Paragraph", "Compact"):
            s.font.size = Pt(12)
    d.save(path)


def set_run_font(run, size=None, bold=None):
    run.font.name = FONT
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.insert(0, rfonts)
    for a in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(qn(a), FONT)
    if size:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    run.font.color.rgb = RGBColor(0, 0, 0)


def add_page_number(section):
    p = section.footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    for tag, text in (("begin", None), (None, "PAGE"), ("end", None)):
        if tag:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), tag)
        else:
            el = OxmlElement("w:instrText")
            el.set(qn("xml:space"), "preserve")
            el.text = text
        run._element.append(el)
    set_run_font(run, 10)


def style_table(t):
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = True
    tblPr = t._element.tblPr
    for old in tblPr.findall(qn("w:tblBorders")):
        tblPr.remove(old)
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "bottom", "insideH"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:color"), "000000")
        borders.append(el)
    # schema order: ... tblW, jc, tblCellSpacing, tblInd, tblBorders, shd, tblLayout, tblCellMar, tblLook
    anchor = tblPr.find(qn("w:tblLayout"))
    if anchor is None:
        anchor = tblPr.find(qn("w:tblLook"))
    if anchor is not None:
        anchor.addprevious(borders)
    else:
        tblPr.append(borders)
    ncols = len(t.columns)
    size = 9 if ncols <= 6 else 8
    for i, row in enumerate(t.rows):
        for cell in row.cells:
            for p in cell.paragraphs:
                p.alignment = WD_ALIGN_PARAGRAPH.LEFT
                pf = p.paragraph_format
                pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
                pf.space_before = Pt(1)
                pf.space_after = Pt(1)
                for r in p.runs:
                    set_run_font(r, size, bold=True if i == 0 else None)
    # repeat header row on page breaks
    trPr = t.rows[0]._tr.get_or_add_trPr()
    if trPr.find(qn("w:tblHeader")) is None:
        h = OxmlElement("w:tblHeader")
        h.set(qn("w:val"), "true")
        trPr.append(h)


def format_docx(path: Path):
    d = Document(path)
    for s in d.sections:
        s.top_margin = s.bottom_margin = Cm(2.54)
        s.left_margin = s.right_margin = Cm(2.54)
        add_page_number(s)
    heading_sizes = {"Title": 16, "Heading 1": 14, "Heading 2": 12, "Heading 3": 12}
    for p in d.paragraphs:
        sname = p.style.name
        pf = p.paragraph_format
        if sname in heading_sizes:
            for r in p.runs:
                set_run_font(r, heading_sizes[sname], bold=True)
                if sname == "Heading 3":
                    r.font.italic = True
            pf.space_before = Pt(12)
            pf.space_after = Pt(6)
            pf.keep_with_next = True
            if sname == "Title":
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            continue
        if sname in ("Figure Caption", "Table Caption", "Image Caption", "Captioned Figure"):
            for r in p.runs:
                set_run_font(r, 10)
            pf.line_spacing = 1.0
            pf.space_after = Pt(10 if sname == "Figure Caption" else 4)
            pf.keep_with_next = sname == "Table Caption"
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
            continue
        if p._element.xpath(".//w:drawing"):
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            pf.keep_with_next = True
            pf.line_spacing = 1.0
            continue
        if sname == "Bibliography":
            for r in p.runs:
                set_run_font(r, 11)
            pf.line_spacing = 1.15
            pf.space_after = Pt(4)
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            continue
        for r in p.runs:
            set_run_font(r, 12)
        if p._element.xpath(".//m:oMathPara"):
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        elif sname not in ("Author", "Date", "Subtitle"):
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        pf.line_spacing = 1.5
        pf.space_after = Pt(6)
    for t in d.tables:
        style_table(t)
    # style defaults (covers runs created by pandoc without explicit fonts, e.g. in math text)
    for sname in ("Normal", "Body Text", "First Paragraph", "Compact"):
        try:
            st = d.styles[sname]
            st.font.name = FONT
            st.font.size = Pt(12)
            st.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
        except (KeyError, AttributeError):
            pass
    d.save(path)


PDF_CSS = """
@page { size: A4; margin: 2.54cm; @bottom-center { content: counter(page); font-family: 'Times New Roman',
        'Liberation Serif', serif; font-size: 10pt; } }
body { font-family: 'Times New Roman', 'Liberation Serif', serif; font-size: 12pt; line-height: 1.5;
       text-align: justify; color: #000; max-width: none; margin: 0; }
h1.title { font-size: 16pt; text-align: center; line-height: 1.3; }
h1 { font-size: 14pt; margin: 14pt 0 6pt; } h2 { font-size: 12pt; margin: 12pt 0 6pt; }
h3 { font-size: 12pt; font-style: italic; }
h1, h2, h3 { page-break-after: avoid; break-after: avoid; text-align: left; }
p { margin: 0 0 6pt; } figure { margin: 8pt 0; text-align: center; page-break-inside: avoid; }
img { max-width: 100%; }
table { border-collapse: collapse; margin: 4pt auto 10pt; font-size: 8.5pt; line-height: 1.15;
        border-top: 1px solid #000; border-bottom: 1px solid #000; page-break-inside: auto; }
th, td { padding: 1.5pt 4pt; text-align: left; vertical-align: top; } thead th { border-bottom: 1px solid #000; }
tr { page-break-inside: avoid; }
div[data-custom-style="Figure Caption"] p, div[data-custom-style="Table Caption"] p { font-size: 10pt;
        line-height: 1.2; margin-bottom: 8pt; } div[data-custom-style="Table Caption"] { page-break-after: avoid; }
div[data-custom-style="Author"] p { text-align: center; }
.csl-entry { font-size: 11pt; line-height: 1.2; margin-bottom: 4pt; text-align: left; padding-left: 1.5em;
             text-indent: -1.5em; }
math { font-size: 1.05em; }
"""
CHROME = "/opt/pw-browsers/chromium-1194/chrome-linux/chrome"


def to_pdf(rmd: Path, out_pdf: Path, csl: str):
    """PDF for visual inspection, rendered from the same Markdown via pandoc (MathML) + headless
    Chromium, because LibreOffice's headless export drops inline OMML equations."""
    css = MS / "styles" / "print.css"
    css.write_text(PDF_CSS)
    html = out_pdf.with_suffix(".html")
    subprocess.run(["pandoc", str(rmd), "-f", "markdown+tex_math_dollars+pipe_tables+fenced_divs", "--citeproc",
                    "--bibliography", str(ROOT / "literature" / "verified_references.bib"), "--csl", csl,
                    "--number-sections", "--mathml", "--standalone", "--embed-resources", "--css", str(css),
                    "--resource-path", str(ROOT), "--metadata", "lang=en", "-o", str(html)], check=True)
    subprocess.run([CHROME, "--headless", "--no-sandbox", "--disable-gpu", "--no-pdf-header-footer",
                    f"--print-to-pdf={out_pdf}", html.as_uri()], check=True, capture_output=True, timeout=600)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", default=None, help="single Markdown file; default: manuscript/sections/*.md in order")
    ap.add_argument("--out", default=str(MS / "manuscript_final.docx"))
    ap.add_argument("--csl", default=str(MS / "styles" / "elsevier-harvard.csl"))
    ap.add_argument("--no-pdf", action="store_true")
    ap.add_argument("--sections-dir", default=str(MS / "sections"))
    ap.add_argument("--rendered", default=str(MS / "manuscript_rendered.md"))
    a = ap.parse_args(argv)
    if a.source:
        src = Path(a.source).read_text()
    else:
        src = "\n\n".join(p.read_text() for p in sorted(Path(a.sections_dir).glob("*.md")))
    rendered = insert_objects(fill_numbers(src))
    rmd = Path(a.rendered)
    rmd.write_text(rendered)
    ref = MS / "styles" / "reference.docx"
    reference_doc(ref)
    out = Path(a.out).resolve()
    subprocess.run(["pandoc", str(rmd), "-f", "markdown+tex_math_dollars+pipe_tables+fenced_divs", "--citeproc",
                    "--bibliography", str(ROOT / "literature" / "verified_references.bib"), "--csl", a.csl,
                    "--reference-doc", str(ref), "--resource-path", str(ROOT), "--number-sections", "-o", str(out)], check=True)
    format_docx(out)
    if not a.no_pdf:
        to_pdf(rmd, out.with_suffix(".pdf"), a.csl)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
